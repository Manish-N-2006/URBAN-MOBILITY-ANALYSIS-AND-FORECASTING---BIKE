        span("Chronological Train/Validation Split Evaluation (Held-Out 7 Days)", class = "fw-bold"),
        span(class = "badge bg-info", "Out-of-Sample Accuracy")
      ),
      card_body(
        callout_card(
          title = "Methodology: Chronological vs. Random Splitting",
          message = "In time-series forecasting, random train/test splitting introduces severe temporal data leakage. We strictly preserve the temporal ordering: models are trained on the first ~54 days and evaluated on the final 7 consecutive days of historical observations. Performance metrics (MAE, RMSE, MAPE) are calculated exclusively on these held-out days.",
