              title = "Predictive Modeling Transparency Notice",
              message = "Forecasts are generated by fitting an Auto-Regressive Integrated Moving Average (ARIMA) with seasonal lag patterns. Forecasts represent expected daily ride demand under normal urban mobility conditions. Extreme weather events, local strikes, or platform surge disruptions are not modeled. Accuracy is indicative and not guaranteed.",
              type = "warning"
            )
          )
        )
      )
    )
  )
}

forecasting_server <- function(id, shared_data) {
  moduleServer(id, function(input, output, session) {
    
    # Populate zone choices dynamically from daily panel
    observe({
      req(shared_data$daily_panel)
      top_zones <- shared_data$daily_panel %>%
        group_by(pickup_zone) %>%
        summarise(total = sum(demand_requests), .groups = "drop") %>%
        arrange(desc(total)) %>%
        pull(pickup_zone)
      
      updateSelectInput(session, "selected_zone", choices = top_zones, selected = top_zones[1])
    })
    
    # Reactive active time series
    active_ts_data <- reactive({
      req(input$selected_zone, shared_data$daily_panel, shared_data$rides_df)
      
      if (input$forecast_service == "Bike Taxi Only Demand") {
        # Build bike-only daily panel
        panel <- build_zone_daily_panel(shared_data$rides_df, service_filter = c("bike", "bike lite"), min_zone_total_rides = 10)
      } else {
        panel <- shared_data$daily_panel
      }
      
      prepare_zone_timeseries(panel, input$selected_zone)
    })
    
    # 1. Validation Evaluation Reactive
    eval_results <- reactive({
      ts_info <- active_ts_data()
      req(ts_info)
      evaluate_models_chronological(ts_info, test_days = 7)
    })
    
    # Render Metrics Comparison Table
    output$metrics_table <- renderTable({
      res <- eval_results()
      if (!res$is_valid) {
        return(data.frame(Status = res$reason))
      }
      res$comparison_table
    }, striped = TRUE, hover = TRUE, bordered = TRUE, width = "100%")
    
    # Validation Holdout Plot
    output$validation_plot <- renderPlotly({
      res <- eval_results()
      req(res$is_valid)
      
      df_eval <- res$eval_data
      
      p <- plot_ly(df_eval, x = ~Date) %>%
        add_lines(y = ~Actual, name = "Actual Demand", line = list(color = "#f8fafc", width = 3)) %>%
        add_lines(y = ~Baseline_Forecast, name = "Seasonal Naive (Baseline)", line = list(color = "#f59e0b", width = 2, dash = "dash")) %>%
        add_lines(y = ~Model_Forecast, name = "Auto-ARIMA", line = list(color = "#0284c7", width = 2)) %>%
        layout(
          xaxis = list(title = "Holdout Test Date"),
          yaxis = list(title = "Requests / Day"),
          hovermode = "x unified"
        )
      
      style_plotly(p)
    })
    
    # 2. Out-of-Sample 7-Day Forecast Reactive
    forecast_results <- reactive({
      ts_info <- active_ts_data()
      req(ts_info)
      generate_zone_forecast(ts_info, horizon = 7)
    })
    
    # Forecast Plot with Prediction Intervals
    output$forecast_plot <- renderPlotly({
      fc <- forecast_results()
      req(fc$is_valid)
      
      hist_df <- tail(fc$historical_data, 28) # Show last 4 weeks of history
      fc_df <- fc$forecast_table
      
      p <- plot_ly() %>%
        # 95% Confidence Interval Band
        add_ribbons(
          data = fc_df,
          x = ~Date,
          ymin = ~Lower_95,
          ymax = ~Upper_95,
          name = "95% Prediction Interval",
          fillcolor = "rgba(2, 132, 199, 0.15)",
          line = list(color = "transparent")
        ) %>%
        # 80% Confidence Interval Band
        add_ribbons(
          data = fc_df,
          x = ~Date,
          ymin = ~Lower_80,
          ymax = ~Upper_80,
          name = "80% Prediction Interval",
          fillcolor = "rgba(2, 132, 199, 0.28)",
          line = list(color = "transparent")
        ) %>%
        # Historical Actuals
        add_lines(
          data = hist_df,
          x = ~Date,
          y = ~Demand,
          name = "Historical Demand",
          line = list(color = "#94a3b8", width = 2)
        ) %>%
        # Projected Mean Forecast
        add_lines(
          data = fc_df,
          x = ~Date,
          y = ~Forecast,
          name = "7-Day Projected Forecast",
          line = list(color = "#38bdf8", width = 3)
        ) %>%
        layout(
          xaxis = list(title = "Date"),
          yaxis = list(title = "Daily Ride Demand Requests"),
          hovermode = "x unified"
        )
      
      style_plotly(p)
    })
    
    # Forecast Values Table
    output$forecast_values_table <- renderTable({
      fc <- forecast_results()
      req(fc$is_valid)
      
      tbl <- fc$forecast_table
      tbl$Date <- as.character(tbl$Date)
      tbl
    }, striped = TRUE, hover = TRUE, bordered = TRUE, width = "100%")
    
  })
}
