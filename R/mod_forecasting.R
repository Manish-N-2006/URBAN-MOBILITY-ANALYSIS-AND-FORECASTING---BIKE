            ns("forecast_service"),
            "Demand Mode:",
            choices = c("All Services Demand", "Bike Taxi Only Demand"),
            selected = "All Services Demand"
          ),
          div(
            style = "display: flex; align-items: flex-end; height: 100%;",
            actionButton(ns("run_forecast_btn"), "Update Forecast", icon = icon("chart-line"), class = "btn-primary w-100")
